import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { api } from "@/convex/_generated/api";
import type { Id } from "@/convex/_generated/dataModel";
import { useMutation, useQuery } from "convex/react";
import {
  CalendarClock,
  CalendarPlus,
  CheckCircle2,
  Clock3,
  FileClock,
  ListChecks,
  MailPlus,
  ScrollText,
  ThumbsDown,
} from "lucide-react";
import { useState } from "react";
import { toast } from "sonner";

// ---------------------------------------------------------------------
// Feature 2 — the review desk for hearing-outcome proposals.
//
// Every proposal generated by "Record hearing outcome" is listed here
// with its decision state. An authorized lawyer (hearing.manage) can
// approve each item individually — editing the payload inline — reject
// it with a reason, or bulk-approve the whole pending set for a hearing.
// Deadline proposals display their source line and calculation rule, and
// require the order.record capability (enforced again server-side).
// Nothing reaches the record or the client until a decision is made;
// rejected items stay visible for audit.
// ---------------------------------------------------------------------

const KIND_META: Record<string, { label: string; icon: typeof ListChecks }> = {
  chronology: { label: "Chronology", icon: ScrollText },
  task: { label: "Task", icon: ListChecks },
  deadline: { label: "Deadline", icon: CalendarClock },
  client_update: { label: "Client update", icon: MailPlus },
  next_hearing: { label: "Next hearing", icon: CalendarPlus },
  hearing_pack: { label: "Hearing Pack", icon: FileClock },
};

type ProposalRow = {
  _id: Id<"outcomeProposals">;
  hearingId: Id<"hearings">;
  kind: string;
  title: string;
  payload: Record<string, unknown>;
  status: "pending" | "approved" | "rejected";
  deadlineSource?: string;
  deadlineRule?: string;
  decisionNote?: string;
  edited: boolean;
};

/** IST due date for display next to a deadline's rule. */
function dueLabel(payload: Record<string, unknown>): string | null {
  const dueAt = payload.dueAt;
  if (typeof dueAt !== "number") return null;
  return new Date(dueAt).toLocaleDateString("en-IN", {
    timeZone: "Asia/Kolkata",
    day: "numeric",
    month: "short",
    year: "numeric",
  });
}

export function ProposalReviewPanel({
  matterId,
  onOpenPack,
}: {
  matterId: Id<"matters">;
  /** When a hearing_pack proposal is approved, offer the pack builder. */
  onOpenPack?: () => void;
}) {
  const caps = useQuery(api.workspace.myCapabilities);
  const canManage = caps?.capabilities.includes("hearing.manage") ?? false;
  const canRecordOrders = caps?.capabilities.includes("order.record") ?? false;

  const proposals = useQuery(
    api.outcomeProposals.listForMatter,
    matterId ? { matterId } : "skip",
  );

  const approve = useMutation(api.outcomeProposals.approveProposal);
  const approveAll = useMutation(api.outcomeProposals.approveAllForHearing);
  const reject = useMutation(api.outcomeProposals.rejectProposal);
  const [busyId, setBusyId] = useState<string | null>(null);
  const [bulkBusy, setBulkBusy] = useState<string | null>(null);

  // --- edit & approve dialog state ---
  const [editRow, setEditRow] = useState<ProposalRow | null>(null);
  const [editTitle, setEditTitle] = useState("");
  const [editBody, setEditBody] = useState("");

  const openEdit = (p: ProposalRow) => {
    setEditRow(p);
    const payload = (p.payload ?? {}) as Record<string, unknown>;
    setEditTitle(String(payload.title ?? p.title));
    setEditBody(String(payload.body ?? payload.detail ?? ""));
  };

  const submitEdit = async () => {
    if (!editRow) return;
    setBusyId(editRow._id);
    try {
      const payload: Record<string, unknown> = {
        ...editRow.payload,
        title: editTitle.trim().slice(0, 200),
      };
      if (editRow.kind === "client_update") payload.body = editBody.slice(0, 20000);
      if (editRow.kind === "chronology") payload.detail = editBody.slice(0, 4000);
      await approve({ proposalId: editRow._id, editedPayload: payload });
      toast.success("Approved with your edits.");
      setEditRow(null);
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "Could not approve.");
    } finally {
      setBusyId(null);
    }
  };

  const approveOne = async (p: ProposalRow) => {
    setBusyId(p._id);
    try {
      const res = await approve({ proposalId: p._id });
      if (res.kind === "hearing_pack") {
        toast.success("Noted — open the pack builder to refresh the checklist.", {
          action: onOpenPack
            ? { label: "Open pack", onClick: onOpenPack }
            : undefined,
        });
      } else {
        toast.success(`Approved — ${KIND_META[p.kind]?.label ?? p.kind} created.`);
      }
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "Could not approve.");
    } finally {
      setBusyId(null);
    }
  };

  const rejectOne = async (p: ProposalRow) => {
    const note = window.prompt(
      "Reason for rejecting (kept on the audit trail):",
      "",
    );
    if (note === null) return; // cancelled — the proposal stays pending
    setBusyId(p._id);
    try {
      await reject({ proposalId: p._id, note: note || undefined });
      toast.success("Rejected — kept on the audit trail.");
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "Could not reject.");
    } finally {
      setBusyId(null);
    }
  };

  const bulkApprove = async (hearingId: Id<"hearings">) => {
    setBulkBusy(hearingId);
    try {
      const res = await approveAll({ hearingId });
      toast.success(
        res.approved === 0 && res.skipped === 0
          ? "Nothing pending for that hearing."
          : `Bulk approved ${res.approved} item${res.approved === 1 ? "" : "s"}${res.skipped ? `, ${res.skipped} skipped — review them below` : ""}.`,
      );
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "Bulk approval failed.");
    } finally {
      setBulkBusy(null);
    }
  };

  if (caps === undefined || proposals === undefined) {
    return (
      <div className="rule-frame bg-card p-4 text-sm ink-faded">
        Retrieving proposals…
      </div>
    );
  }

  const pending = proposals.filter((p) => p.status === "pending");
  const decided = proposals.filter((p) => p.status !== "pending");
  // Pending proposals grouped per hearing, so bulk approval targets one
  // coherent set (the server mutation works per hearing).
  const byHearing = new Map<Id<"hearings">, ProposalRow[]>();
  for (const p of pending) {
    const list = byHearing.get(p.hearingId) ?? [];
    list.push(p);
    byHearing.set(p.hearingId, list);
  }

  return (
    <div className="space-y-3">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div>
          <h3 className="font-serif text-lg font-semibold">
            Outcome review desk
          </h3>
          <p className="text-sm text-muted-foreground">
            Nothing from a recorded outcome is applied until you decide it here.
          </p>
        </div>
        {pending.length > 0 && (
          <Badge variant="outline">{pending.length} pending</Badge>
        )}
      </div>

      {proposals.length === 0 ? (
        <Card className="border-dashed">
          <CardContent className="py-8 text-center text-sm ink-faded">
            No outcome proposals on this matter yet. Record a hearing outcome to
            generate reviewable follow-ups.
          </CardContent>
        </Card>
      ) : (
        <>
          {pending.map((p) => {
            const Icon = KIND_META[p.kind]?.icon;
            return (
              <div
                key={p._id}
                className="rule-frame bg-card p-4"
                data-testid={`proposal-${p.kind}`}
              >
                <div className="flex flex-wrap items-start justify-between gap-3">
                  <div className="min-w-0">
                    <div className="flex flex-wrap items-center gap-2">
                      {Icon && (
                        <span className="type-label flex items-center gap-1.5 ink-faded">
                          <Icon className="size-3.5" aria-hidden="true" />
                          {KIND_META[p.kind]?.label ?? p.kind}
                        </span>
                      )}
                      {p.kind === "deadline" && (
                        <Badge variant="outline" className="text-xs">
                          critical — explicit approval
                        </Badge>
                      )}
                      {p.edited && (
                        <Badge variant="outline" className="text-xs">
                          edited
                        </Badge>
                      )}
                    </div>
                    <p className="mt-1 text-sm font-medium">{p.title}</p>
                    {p.kind === "deadline" && (
                      <div className="mt-1.5 space-y-0.5 text-xs text-muted-foreground">
                        {dueLabel(p.payload) && (
                          <p className="flex items-center gap-1.5">
                            <Clock3 className="size-3.5" aria-hidden="true" />
                            Due {dueLabel(p.payload)}
                          </p>
                        )}
                        {p.deadlineSource && (
                          <p className="italic">
                            Source: “{p.deadlineSource}”
                          </p>
                        )}
                        {p.deadlineRule && <p>Rule: {p.deadlineRule}</p>}
                      </div>
                    )}
                    {(p.kind === "task" ||
                      p.kind === "chronology" ||
                      p.kind === "client_update") && (
                      <p className="mt-1 line-clamp-3 whitespace-pre-wrap text-xs text-muted-foreground">
                        {String(
                          p.payload.body ??
                            p.payload.detail ??
                            p.payload.title ??
                            "",
                        )}
                      </p>
                    )}
                    {p.kind === "next_hearing" &&
                      typeof p.payload.at === "number" && (
                        <p className="mt-1 text-xs text-muted-foreground">
                          {new Date(p.payload.at).toLocaleString("en-IN", {
                            timeZone: "Asia/Kolkata",
                          })}
                        </p>
                      )}
                  </div>
                  {canManage && (
                    <div className="flex shrink-0 flex-wrap items-center gap-2">
                      {p.kind === "deadline" && !canRecordOrders && (
                        <span className="type-label text-[#8a6a33]">
                          Needs record-orders permission
                        </span>
                      )}
                      <Button
                        size="sm"
                        variant="outline"
                        disabled={busyId === p._id}
                        onClick={() => openEdit(p)}
                      >
                        Edit &amp; approve
                      </Button>
                      <Button
                        size="sm"
                        disabled={busyId === p._id}
                        onClick={() => void approveOne(p)}
                      >
                        Approve
                      </Button>
                      <Button
                        size="sm"
                        variant="ghost"
                        className="text-destructive"
                        disabled={busyId === p._id}
                        onClick={() => void rejectOne(p)}
                      >
                        <ThumbsDown className="size-4" aria-hidden="true" />
                        Reject
                      </Button>
                    </div>
                  )}
                </div>
              </div>
            );
          })}

          {[...byHearing.entries()].map(([hid, rows]) => (
            <div
              key={hid}
              className="rule-frame flex flex-wrap items-center justify-between gap-3 bg-card p-4"
            >
              <div className="min-w-0">
                <p className="text-sm font-medium">
                  Bulk approve {rows.length} pending item
                  {rows.length === 1 ? "" : "s"} from this hearing
                </p>
                {rows.some(
                  (r) => r.kind === "deadline" || r.kind === "next_hearing",
                ) &&
                  !canRecordOrders && (
                    <p className="mt-0.5 text-xs text-[#8a6a33]">
                      Includes deadline items — needs the record-orders
                      permission.
                    </p>
                  )}
              </div>
              <Button
                size="sm"
                variant="outline"
                disabled={bulkBusy === hid}
                onClick={() => void bulkApprove(hid)}
              >
                <CheckCircle2 className="size-4" aria-hidden="true" />
                Approve all
              </Button>
            </div>
          ))}

          {decided.length > 0 && (
            <details className="rule-frame bg-card p-4">
              <summary className="cursor-pointer text-sm font-medium">
                Decision trail ({decided.length}) — approved and rejected items
                are kept for audit
              </summary>
              <ul className="mt-3 space-y-2">
                {decided.map((p) => (
                  <li
                    key={p._id}
                    className="flex flex-wrap items-center gap-2 text-sm"
                  >
                    <Badge
                      variant={p.status === "approved" ? "default" : "destructive"}
                      className="text-xs"
                    >
                      {p.status}
                    </Badge>
                    <span className="min-w-0 truncate">{p.title}</span>
                    {p.decisionNote && (
                      <span className="type-label ink-faded">
                        “{p.decisionNote}”
                      </span>
                    )}
                  </li>
                ))}
              </ul>
            </details>
          )}
        </>
      )}

      {/* Edit & approve dialog — the lawyer's review before materializing. */}
      <Dialog open={!!editRow} onOpenChange={(v) => !v && setEditRow(null)}>
        <DialogContent className="max-h-[85vh] overflow-y-auto">
          <DialogHeader>
            <DialogTitle className="font-serif">
              Review before approving
            </DialogTitle>
            <DialogDescription>
              Your edits become the created record; the original proposal is
              preserved on the audit trail.
            </DialogDescription>
          </DialogHeader>
          <div className="space-y-3">
            <div className="space-y-1.5">
              <Label htmlFor="pr-title">Title</Label>
              <Input
                id="pr-title"
                value={editTitle}
                onChange={(e) => setEditTitle(e.target.value)}
              />
            </div>
            {(editRow?.kind === "client_update" ||
              editRow?.kind === "chronology") && (
              <div className="space-y-1.5">
                <Label htmlFor="pr-body">
                  {editRow.kind === "client_update" ? "Message body" : "Detail"}
                </Label>
                <Textarea
                  id="pr-body"
                  rows={6}
                  value={editBody}
                  onChange={(e) => setEditBody(e.target.value)}
                />
              </div>
            )}
            {editRow?.kind === "deadline" && editRow.deadlineRule && (
              <p className="rounded bg-muted/50 p-2 text-xs text-muted-foreground">
                Rule: {editRow.deadlineRule}
                {editRow.deadlineSource
                  ? ` — source: “${editRow.deadlineSource}”`
                  : ""}
              </p>
            )}
            <div className="flex justify-end gap-2">
              <Button variant="ghost" onClick={() => setEditRow(null)}>
                Cancel
              </Button>
              <Button
                disabled={busyId === editRow?._id || !editTitle.trim()}
                onClick={() => void submitEdit()}
              >
                <CheckCircle2 className="size-4" aria-hidden="true" />
                Approve with edits
              </Button>
            </div>
          </div>
        </DialogContent>
      </Dialog>
    </div>
  );
}
