export const GAZETTE_CA_PEMS: string[] = [
  ISRG_ROOT_X1,
  ROOT_YR_CROSS_SIGNED,
  LE_INTERMEDIATE_YR2,
];

export type PinnedGetResult = {
  status: number;
  contentType: string;
  bytes: Uint8Array;
};

/**
 * Plain GET with the pinned PUBLIC anchors. Mirrors the fetch() path the
 * connector already uses (follows ≤2 redirects; never downgrades to
 * http://). TLS verification is ON for every hop — a failure REJECTS and
 * the caller records it like any other retrieval failure.
 */
export function httpsGetWithPinnedCa(
  url: string,
  headers: Record<string, string>,
  timeoutMs = 45_000,
): Promise<PinnedGetResult> {
  const doGet = (target: string, hopsLeft: number): Promise<PinnedGetResult> =>
    new Promise((resolve, reject) => {
      const req = https.request(
        target,
        {
          method: "GET",
          ca: GAZETTE_CA_PEMS,
          headers,
          timeout: timeoutMs,
        },
        (res) => {
          const status = res.statusCode ?? 0;
          // Redirect parity with fetch()'s default follow behaviour.
          if ([301, 302, 303, 307, 308].includes(status) && res.headers.location) {
            res.resume(); // drain
            if (hopsLeft <= 0) {
              reject(new Error(`Too many redirects retrieving ${url}`));
              return;
            }
            const next = new URL(res.headers.location, target).toString();
            if (!next.startsWith("https://")) {
              reject(new Error(`Refusing non-HTTPS redirect to ${next}`));
              return;
            }
            doGet(next, hopsLeft - 1).then(resolve, reject);
            return;
          }
          const contentType = res.headers["content-type"] ?? "";
          const chunks: Buffer[] = [];
          res.on("data", (c: Buffer) => chunks.push(c));
          res.on("end", () =>
            resolve({
              status,
              contentType,
              bytes: new Uint8Array(Buffer.concat(chunks)),
            }),
          );
          res.on("error", reject);
        },
      );
      req.on("timeout", () => req.destroy(new Error(`Request timed out after ${timeoutMs}ms`)));
      req.on("error", reject);
      req.end();
    });
  return doGet(url, 2);
}
