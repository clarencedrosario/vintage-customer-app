// =====================================================================
// Pinned PUBLIC trust anchors + node:https GET helper (turn 26).
//
// WHY THIS EXISTS — eGazette (egazette.gov.in) serves an INCOMPLETE
// certificate chain: leaf ← "YR2" (Let's Encrypt intermediate) only.
// Node's global fetch (undici) offers no way to supply extra trust
// anchors, so chain building fails even though the certificate is
// perfectly valid — browsers succeed by fetching the missing
// intermediate from the chain's AIA pointer (the standard AIA trust
// model). Two options existed:
//   (a) disable certificate verification — REFUSED, and
//   (b) pin the PUBLIC root/intermediates as extra `ca` anchors so the
//       full chain verifies. Chosen.
//
// WHAT IS PINNED (all PUBLIC Let's Encrypt / ISRG certificates, not
// secrets; re-derivable from the AIA URLs printed below):
//   1. ISRG Root X1   — self-signed trust anchor (also in the system
//                       store, but this env's store lacks it, so it is
//                       pinned explicitly). AIA: http://x1.i.lencr.org/
//                       sha256 96BCEC06264976F37460779ACF28C5A7CFE8A3
//                       C0AAE11A8FFCEE05C0BDDF08C6
//   2. Root YR        — cross-signed by ISRG Root X1 (AIA of YR2).
//                       AIA: http://yr.i.lencr.org/
//                       sha256 072639D0B140D5BFFAE16AD9C3F6CC6086040621
//                       F51E61A6D46A8915C07CF76
//   3. YR2            — the intermediate the server actually sends.
//                       AIA: http://yr2.i.lencr.org/
//                       sha256 238B85A0099C65B970477D5724F1A1D475CE505
//                       8CFE4EFA8733899BDB863C47
//
// GUARANTEES: certificate verification stays FULLY ENABLED (custom `ca`
// REPLACES the default store with these anchors; an untrusted chain
// still fails). No access control is bypassed — plain GET of published
// documents only. Used ONLY by notices flagged
// `tlsFix: "lets-encrypt-aia"` in sourceNotices.ts; every other notice
// keeps the plain global-fetch path.
// =====================================================================

